/**
 * Returns the hex color for a given color name (case-insensitive, trims whitespace).
 * Returns null if the color is not found in the palette.
 */
export function getColorHex(name: string): string | null {
  if (!name) return null;
  const normalized = name.trim().toLowerCase();
  const found = COLOR_PALETTE.find(
    (c) => c.name.toLowerCase() === normalized
  );
  return found?.hex ?? null;
}
